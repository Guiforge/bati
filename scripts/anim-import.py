#!/usr/bin/env python3
"""Bring the validated exercise loops from the animation pilot cache into the app.

    scripts/anim-import.py picks <picks.json>      # six-frame loops from key pictures (lots 9-11)
    scripts/anim-import.py site <slug> [<slug>..]  # an earlier flip-book, copied from site/<slug>/

Both write assets/images/exercises/anim/<slug>/k1..kN.webp (the distinct frames), merge the slug's
steps (frame index, milliseconds) into anim/manifest.json, then regenerate
constants/exerciseFrames.ts (Metro needs one literal `require` per file) and the provenance entry.
Swapping a lot to another rendering (the comic-book one) is one rerun of `picks` with its file.
The pilot is outside the repo: ~/.cache/bati-anim-pilot-v3 (scripts/anim-pilot-v3.py).
"""
import hashlib
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PILOT = pathlib.Path.home() / ".cache" / "bati-anim-pilot-v3"
OUT = ROOT / "assets" / "images" / "exercises" / "anim"
MANIFEST = OUT / "manifest.json"
GENERATED = ROOT / "constants" / "exerciseFrames.ts"
PROVENANCE = ROOT / "scripts" / "provenance.json"
A_KEY = {"pushups": "k1", "diamond_pushup": "k1", "knee_pushup": "k1"}  # the rest have their A at k4
CYCLE_MS = {"jump_squat": 2000}  # one rep in 3 s, the jump squat in 2
ORDER = (0, 1, 2, 3, 2, 1)  # k1 k2 k3 k4 k3 k2
WEIGHT = (45, 45, 45, 70, 45, 45)


def load():
    return json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}


def from_picks(path):
    manifest = load()
    for slug, keys in json.loads(pathlib.Path(path).read_text()).items():
        if "use_previous" in keys:
            print(f"{slug}: keeps its earlier version, use `site {slug}`")
            continue
        a = A_KEY.get(slug, "k4")
        d = OUT / slug
        d.mkdir(parents=True, exist_ok=True)
        for i, k in enumerate(("k1", "k2", "k3", "k4"), 1):
            src = PILOT / "A" / f"{slug}.png" if k == a else PILOT / keys[k]
            subprocess.run(["magick", str(src), "-resize", "480x480!", "-quality", "82",
                            str(d / f"k{i}.webp")], check=True)
        total = CYCLE_MS.get(slug, 2950)
        manifest[slug] = [[i, round(total * WEIGHT[n] / sum(WEIGHT))] for n, i in enumerate(ORDER)]
        print(slug, "frames: 4")
    return manifest


def from_site(slugs):
    manifest = load()
    for slug in slugs:
        s = PILOT / "site" / slug
        poses = sorted(s.glob("pose_k*.webp"), key=lambda p: int(p.stem[6:]))
        delays = [int(x) * 10 for x in subprocess.run(
            ["identify", "-format", "%T ", str(s / "cuts.webp")], check=True,
            capture_output=True, text=True).stdout.split()]
        assert len(poses) == len(delays), f"{slug}: {len(poses)} poses, {len(delays)} cuts"
        distinct, steps = {}, []
        for p, ms in zip(poses, delays):
            h = hashlib.md5(p.read_bytes()).hexdigest()
            distinct.setdefault(h, (len(distinct), p))
            steps.append([distinct[h][0], ms])
        d = OUT / slug
        d.mkdir(parents=True, exist_ok=True)
        for i, p in distinct.values():
            (d / f"k{i + 1}.webp").write_bytes(p.read_bytes())
        manifest[slug] = steps
        print(slug, "frames:", len(distinct), "steps:", len(steps))
    return manifest


def write(manifest):
    manifest = dict(sorted(manifest.items()))
    MANIFEST.write_text(json.dumps(manifest) + "\n")
    lines = ["// Generated by scripts/anim-import.py from assets/images/exercises/anim/manifest.json.",
             "// Do not edit: Metro needs one literal require per frame.", "",
             "export type ExerciseLoop = { frames: number[]; steps: [number, number][] };", "",
             "export const EXERCISE_LOOPS: Record<string, ExerciseLoop> = {"]
    for slug, steps in manifest.items():
        n = max(i for i, _ in steps) + 1
        req = ", ".join(f'require("@/assets/images/exercises/anim/{slug}/k{i + 1}.webp")' for i in range(n))
        lines.append(f"  {slug}: {{ frames: [{req}], steps: {json.dumps(steps)} }},")
    lines.append("};")
    GENERATED.write_text("\n".join(lines) + "\n")
    ledger = json.loads(PROVENANCE.read_text())
    ledger["assets/images/exercises/anim/*/*.webp"] = {
        "derived_from": "assets/images/exercises/*.webp",
        "how": "key poses of each movement, drawn as edits of that exercise's still (a jointed mannequin "
        "fixes the pose, FLUX 3 image or gpt-image-2.5-sunburst draws it, every candidate scored blind "
        "and accepted at 4 or more on pose, style, fixed points and anatomy), then shown as a hard-cut "
        "loop. Made by scripts/anim-pilot-v3.py and imported by scripts/anim-import.py: 480 px WebP q82, "
        "or the pilot's own 512 px flip-book frames for the earlier versions. Report: "
        "docs/designs/animations-pilot-v3-report.md",
        "licence": "same as the stills they edit: the API account holder owns the output (BFL Developer "
        "Terms 3.b; OpenAI terms)",
    }
    PROVENANCE.write_text(json.dumps(ledger, indent=2, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    mode, *args = sys.argv[1:]
    write(from_picks(args[0]) if mode == "picks" else from_site(args))
