#!/usr/bin/env python3
"""The accepted buildings' own saturation and value, the reference the ground is measured against (T39).

    python3 scripts/iso/reference_sprites.py            # writes constants/isoSpritesReference.json
    python3 scripts/iso/reference_sprites.py --check    # exits 1 when the file is stale

Reads every assets/images/village/iso/<batiment>/solid.nuit.webp, keeps the opaque pixels (alpha
over 128) and takes their mean saturation and value in HSV, 0 to 1 (PIL's `HSV`, 255 scale).
The file holds each building's means and the pooled mean (`s`, `v`), which is what
__tests__/iso-sol-encre.test.ts compares the ground to; that test also checks the file lists the
buildings that exist, and recomputes it when PIL is installed.
"""

import json
import pathlib
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
IMAGES = ROOT / "assets/images/village/iso"
OUT = ROOT / "constants/isoSpritesReference.json"


def mesure(fin: str = "nuit") -> dict:
    par_batiment = {}
    somme_s = somme_v = n_total = 0
    for f in sorted(IMAGES.glob(f"*/solid.{fin}.webp")):
        im = Image.open(f).convert("RGBA")
        hsv = im.convert("RGB").convert("HSV")
        s_px, v_px, a_px = hsv.getchannel("S").tobytes(), hsv.getchannel("V").tobytes(), im.getchannel("A").tobytes()
        n = s = v = 0
        for i, a in enumerate(a_px):
            if a > 128:
                n += 1
                s += s_px[i]
                v += v_px[i]
        par_batiment[f.parent.name] = {"s": round(s / n / 255, 4), "v": round(v / n / 255, 4), "pixels": n}
        somme_s, somme_v, n_total = somme_s + s, somme_v + v, n_total + n
    return {
        "_doc": "Generated by scripts/iso/reference_sprites.py: do not edit.",
        "s": round(somme_s / n_total / 255, 4),
        "v": round(somme_v / n_total / 255, 4),
        "batiments": par_batiment,
    }


def complet() -> dict:
    """The night reference, plus the pooled day means (the day lawn is read against the unwashed day sprites)."""
    res = mesure()
    j = mesure("jour")
    return {**res, "jour": {"s": j["s"], "v": j["v"]}}


if __name__ == "__main__":
    res = json.dumps(complet(), indent=2) + "\n"
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text() == res else 1)
    OUT.write_text(res)
