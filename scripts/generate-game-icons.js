const fs = require("node:fs");
const path = require("node:path");

const PROJECT_ROOT = path.join(__dirname, "..");

const ICON_ROOT = path.join(
  PROJECT_ROOT,
  "assets",
  "game-icons.net.svg-foreground-white",
  "icons",
  "ffffff",
  "transparent",
  "1x1"
);

const ALLOWLIST_PATH = path.join(PROJECT_ROOT, "src", "icons", "gameIcons.allowlist.json");

const OUT_ALL = path.join(PROJECT_ROOT, "src", "icons", "gameIcons.all.ts");
const OUT_REGISTRY = path.join(PROJECT_ROOT, "src", "icons", "gameIcons.registry.ts");

function walkSvgFiles(dir) {
  /** @type {string[]} */
  const results = [];
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...walkSvgFiles(fullPath));
      continue;
    }
    if (entry.isFile() && entry.name.endsWith(".svg")) {
      results.push(fullPath);
    }
  }
  return results;
}

function toPosix(p) {
  return p.split(path.sep).join("/");
}

function writeFileIfChanged(filePath, content) {
  if (fs.existsSync(filePath)) {
    const current = fs.readFileSync(filePath, "utf8");
    if (current === content) return false;
  }
  fs.writeFileSync(filePath, content, "utf8");
  return true;
}

function main() {
  if (!fs.existsSync(ICON_ROOT)) {
    throw new Error(`Icon root not found: ${ICON_ROOT}`);
  }

  /** @type {string[]} */
  const allSvgs = walkSvgFiles(ICON_ROOT);

  // Build the ALL list as "artist/fileBase"
  const allNames = allSvgs
    .map((abs) => {
      const rel = path.relative(ICON_ROOT, abs);
      const relPosix = toPosix(rel);
      const parts = relPosix.split("/");
      if (parts.length < 2) return null;
      const artist = parts[0];
      const filename = parts[parts.length - 1];
      const base = filename.replace(/\.svg$/, "");
      return `${artist}/${base}`;
    })
    .filter(Boolean);

  allNames.sort();

  const allTs =
    "// This file is auto-generated by scripts/generate-game-icons.js.\n" +
    "// Do not edit by hand.\n\n" +
    `export const ALL_GAME_ICON_NAMES = ${JSON.stringify(allNames, null, 2)} as const;\n\n` +
    "export type AllGameIconName = (typeof ALL_GAME_ICON_NAMES)[number];\n";

  const allowlist = JSON.parse(fs.readFileSync(ALLOWLIST_PATH, "utf8"));
  if (!Array.isArray(allowlist)) {
    throw new Error("Allowlist must be a JSON array of strings.");
  }

  // Validate allowlist exists in ALL
  const allSet = new Set(allNames);
  const missing = allowlist.filter((name) => typeof name !== "string" || !allSet.has(name));
  if (missing.length > 0) {
    throw new Error(
      `Some allowlisted icons were not found under ${ICON_ROOT}:\n${missing.map(String).join("\n")}`
    );
  }

  // Generate registry mapping for allowlist.
  // Use relative require paths to avoid relying on TS path aliases at runtime.
  // Build file path for each icon name.
  const iconLines = allowlist
    .slice()
    .sort()
    .map((name) => {
      const [artist, base] = String(name).split("/");
      const absSvgPath = path.join(ICON_ROOT, artist, `${base}.svg`);
      const relFromRegistry = path.relative(path.join(PROJECT_ROOT, "src", "icons"), absSvgPath);
      const reqPath = `./${toPosix(relFromRegistry)}`;
      return `  "${name}": require("${reqPath}"),`;
    })
    .join("\n");

  const registryTs =
    "// This file is auto-generated by scripts/generate-game-icons.js.\n" +
    "// Do not edit by hand. Update src/icons/gameIcons.allowlist.json and re-run the generator.\n\n" +
    'import type { ImageSourcePropType } from "react-native";\n\n' +
    "export const GAME_ICON_SOURCES = {\n" +
    iconLines +
    "\n} as const satisfies Record<string, ImageSourcePropType>;\n\n" +
    "export type GameIconName = keyof typeof GAME_ICON_SOURCES;\n\n" +
    "export const GAME_ICON_NAMES = Object.keys(GAME_ICON_SOURCES) as GameIconName[];\n\n" +
    "export function isGameIconName(name: string): name is GameIconName {\n" +
    "  return name in GAME_ICON_SOURCES;\n" +
    "}\n\n" +
    "export function getGameIconSource(name: GameIconName): ImageSourcePropType {\n" +
    "  return GAME_ICON_SOURCES[name];\n" +
    "}\n";

  writeFileIfChanged(OUT_ALL, allTs);
  writeFileIfChanged(OUT_REGISTRY, registryTs);
}

main();
