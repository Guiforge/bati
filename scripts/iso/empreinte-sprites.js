// Fingerprint of the village's bundled images, written to components/village/iso/empreinteSprites.ts.
// `node scripts/iso/empreinte-sprites.js` after any sprite change; a jest test fails when it is stale.
const { createHash } = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const RACINE = path.resolve(__dirname, "../..");
const DOSSIERS = [
  "assets/images/village/iso",
  "components/village/iso/mondeTuiles",
  "components/village/iso/planches",
];
const SORTIE = path.join(RACINE, "components/village/iso/empreinteSprites.ts");

function fichiers(dossier) {
  if (!fs.existsSync(dossier)) return [];
  return fs.readdirSync(dossier, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dossier, e.name);
    if (e.isDirectory()) return fichiers(p);
    return /\.(webp|png)$/.test(e.name) ? [p] : [];
  });
}

/** Hash of the names and bytes of every image under `dossiers`: it moves when a pixel does, not per app version. */
function calculer(dossiers = DOSSIERS.map((d) => path.join(RACINE, d))) {
  const h = createHash("sha256");
  for (const f of dossiers.flatMap(fichiers).sort()) {
    h.update(path.relative(RACINE, f)).update(fs.readFileSync(f));
  }
  return h.digest("hex").slice(0, 16);
}

if (require.main === module) {
  fs.writeFileSync(
    SORTIE,
    `// Generated by scripts/iso/empreinte-sprites.js, do not edit.\nexport const EMPREINTE_SPRITES = "${calculer()}";\n`,
  );
}
module.exports = { calculer };
